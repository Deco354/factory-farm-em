"""Uploading adapters, and the models.yaml that loads them into `fc run`.

Every checkpoint goes to its own branch of one private Hugging Face repo and is pinned
by that branch's commit. The generated models.yaml uses the same base repo and revision
the run trained on, so the eval side loads a trained adapter exactly like a released
one: `vllm/<base>:<repo>@<commit>`. The un-adapted base is added by `fc run` itself.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from typing import Any

import yaml


@dataclass(frozen=True)
class UploadedAdapter:
    name: str  # the branch, `<study>--<run>--step-<n>`
    repo: str
    commit: str
    rank: int
    variant: str  # general (treatment arms) or control
    domain: str | None = None
    note: str | None = None


def render_models_yaml(
    *,
    study: str,
    base: str,
    base_revision: str,
    tool_call_parser: str,
    adapters: Sequence[UploadedAdapter],
    server: Mapping[str, Any] | None = None,
) -> str:
    """models.yaml text for `fc run --models`. `server` adds per-base vLLM settings
    (max_model_len, gpu_memory_utilization)."""
    defaults: dict[str, Any] = {
        "base": base,
        "base_revision": base_revision,
        "tool_call_parser": tool_call_parser,
        **(server or {}),
    }
    models = []
    for a in adapters:
        entry: dict[str, Any] = {
            "name": a.name,
            "adapter": a.repo,
            "adapter_revision": a.commit,
            "rank": a.rank,
            "variant": a.variant,
        }
        if a.domain is not None:
            entry["domain"] = a.domain
        if a.note is not None:
            entry["note"] = a.note
        models.append(entry)
    header = (
        f"# Generated by `fc train upload` for study {study}. Each adapter is one checkpoint\n"
        "# branch, pinned by commit. The base is the revision the runs trained on.\n"
    )
    body = yaml.safe_dump(
        {"base_defaults": defaults, "models": models}, sort_keys=False, allow_unicode=True
    )
    return header + body
